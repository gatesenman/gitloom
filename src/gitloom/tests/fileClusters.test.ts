import { describe, it, expect } from 'vitest'
import {
  clusterChangedFiles, filterFilesByCluster, isLikelyAiChange, pathPrefix
} from '../src/renderer/src/lib/fileClusters'

describe('fileClusters', () => {
  it('pathPrefix nests src/*', () => {
    expect(pathPrefix('src/main/foo.ts')).toBe('src/main')
    expect(pathPrefix('README.md')).toBe('README.md')
    expect(pathPrefix('docs/a.md')).toBe('docs')
  })

  it('detects AI author / subject / path', () => {
    expect(isLikelyAiChange({ path: 'a.ts', author: 'dependabot[bot]' })).toBe(true)
    expect(isLikelyAiChange({ path: 'a.ts', subjects: ['feat: generated by copilot'] })).toBe(true)
    expect(isLikelyAiChange({ path: '.cursor/rules.md' })).toBe(true)
    expect(isLikelyAiChange({ path: 'src/a.ts', author: 'Alice' })).toBe(false)
  })

  it('clusters by path, author, and AI tag', () => {
    const clusters = clusterChangedFiles([
      { path: 'src/main/a.ts', author: 'Alice', subjects: ['fix'] },
      { path: 'src/main/b.ts', author: 'Alice' },
      { path: 'src/renderer/c.tsx', author: 'copilot[bot]', subjects: ['ai: polish'] },
      { path: 'docs/x.md', author: 'Bob' }
    ])
    expect(clusters.some((c) => c.kind === 'ai' && c.count >= 1)).toBe(true)
    expect(clusters.some((c) => c.kind === 'author' && c.label === 'Alice' && c.count === 2)).toBe(true)
    expect(clusters.some((c) => c.id === 'path:src/main')).toBe(true)
    const alice = clusters.find((c) => c.id === 'author:Alice')!
    const filtered = filterFilesByCluster(
      [{ path: 'src/main/a.ts' }, { path: 'docs/x.md' }, { path: 'src/main/b.ts' }],
      clusters,
      alice.id
    )
    expect(filtered.map((f) => f.path).sort()).toEqual(['src/main/a.ts', 'src/main/b.ts'])
    expect(filterFilesByCluster([{ path: 'docs/x.md' }], clusters, null)).toHaveLength(1)
  })
})
