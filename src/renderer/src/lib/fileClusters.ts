/** 改动文件聚类：路径前缀 / 作者 / AI 改动启发式 → 可点击筛选 */
export type ClusterKind = 'path' | 'author' | 'ai' | 'other'

export interface ClusterFile {
  path: string
  /** 最近提交作者（可选） */
  author?: string
  /** 相关提交说明，用于 AI 启发式 */
  subjects?: string[]
}

export interface FileCluster {
  id: string
  label: string
  kind: ClusterKind
  /** 白话说明 */
  tip: string
  paths: string[]
  count: number
}

const AI_AUTHOR = /copilot|cursor\[bot\]|chatgpt|openai|claude|anthropic|devin|codegen|codex|dependabot|github-actions|\[bot\]|ai[-_ ]?assistant|gpt-?[0-9]/i
const AI_SUBJECT = /(?:^|\b)(?:ai[:\s]|generated by|co-authored-by:.*(?:bot|copilot|cursor)|signed-off-by:.*bot|autogenerated|llm\b|claude\b|gpt-?[0-9])/i
const AI_PATH = /(^|\/)(\.cursor|\.aider|\.continue|__generated__|generated\/|ai-output)(\/|$)/i

export function isLikelyAiChange(f: ClusterFile): boolean {
  if (f.author && AI_AUTHOR.test(f.author)) return true
  if (f.subjects?.some((s) => AI_SUBJECT.test(s))) return true
  if (AI_PATH.test(f.path.replace(/\\/g, '/'))) return true
  return false
}

/** 路径前缀：取首段；常见 src/app 等再取两段 */
export function pathPrefix(path: string): string {
  const norm = path.replace(/\\/g, '/').replace(/^\.\//, '')
  const segs = norm.split('/').filter(Boolean)
  if (segs.length <= 1) return segs[0] || '（根目录）'
  const top = segs[0]
  if (/^(src|app|apps|packages|services|lib|components|renderer|main|web|frontend|backend|server|client|ui)$/i.test(top) && segs.length >= 2) {
    return `${top}/${segs[1]}`
  }
  return top
}

function sortClusters(a: FileCluster, b: FileCluster): number {
  const kindRank: Record<ClusterKind, number> = { ai: 0, author: 1, path: 2, other: 3 }
  return kindRank[a.kind] - kindRank[b.kind] || b.count - a.count || a.label.localeCompare(b.label, 'zh')
}

/**
 * 按作者 / AI 启发式 / 路径前缀聚类。
 * - 始终产出路径聚类
 * - 有作者信息时额外产出作者聚类
 * - 检测到 AI 痕迹时产出「AI 改动」聚类（可与作者重叠，筛选用 paths）
 */
export function clusterChangedFiles(files: ClusterFile[]): FileCluster[] {
  if (!files.length) return []
  const byPath = new Map<string, string[]>()
  const byAuthor = new Map<string, string[]>()
  const aiPaths: string[] = []

  for (const f of files) {
    const p = f.path.replace(/\\/g, '/')
    const pref = pathPrefix(p)
    if (!byPath.has(pref)) byPath.set(pref, [])
    byPath.get(pref)!.push(p)

    if (f.author?.trim()) {
      const a = f.author.trim()
      if (!byAuthor.has(a)) byAuthor.set(a, [])
      byAuthor.get(a)!.push(p)
    }
    if (isLikelyAiChange(f)) aiPaths.push(p)
  }

  const out: FileCluster[] = []

  if (aiPaths.length) {
    out.push({
      id: 'ai:ai-changes',
      label: 'AI 改动',
      kind: 'ai',
      tip: '作者名、提交说明或路径看起来像 AI/机器人生成',
      paths: [...new Set(aiPaths)],
      count: new Set(aiPaths).size
    })
  }

  for (const [author, paths] of byAuthor) {
    const uniq = [...new Set(paths)]
    // 单一作者且等于全部文件时仍展示，便于筛选；与 AI 标签可并存
    out.push({
      id: `author:${author}`,
      label: author,
      kind: 'author',
      tip: `作者：${author}`,
      paths: uniq,
      count: uniq.length
    })
  }

  for (const [pref, paths] of byPath) {
    const uniq = [...new Set(paths)]
    out.push({
      id: `path:${pref}`,
      label: pref,
      kind: 'path',
      tip: `路径前缀「${pref}」`,
      paths: uniq,
      count: uniq.length
    })
  }

  // 若作者聚类覆盖了全部且只有一个，仍保留路径聚类便于浏览
  return out.sort(sortClusters)
}

/** 按选中聚类 id 过滤；null/空 = 全部 */
export function filterFilesByCluster<T extends { path: string }>(
  files: T[],
  clusters: FileCluster[],
  clusterId: string | null
): T[] {
  if (!clusterId) return files
  const c = clusters.find((x) => x.id === clusterId)
  if (!c) return files
  const set = new Set(c.paths.map((p) => p.replace(/\\/g, '/')))
  return files.filter((f) => set.has(f.path.replace(/\\/g, '/')))
}

