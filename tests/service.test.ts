import { describe, it, expect, beforeEach } from 'vitest'
import { existsSync, readFileSync, writeFileSync, mkdtempSync, statSync } from 'fs'
import { tmpdir } from 'os'
import * as path from 'path'
import { GitService } from '../src/main/git/service'
import { commitAll, sh, tmpRepo, write } from './helpers'

const git = new GitService()

describe('GitService', () => {
  let repo: string
  beforeEach(() => {
    repo = tmpRepo()
    write(repo, 'a.txt', 'one\ntwo\nthree\nfour\nfive\nsix\nseven\neight\nnine\nten\n')
    write(repo, 'src/main.ts', 'export const x = 1\n')
    commitAll(repo, 'init')
  })

  it('detects repos and status', async () => {
    expect(await git.isRepo(repo)).toBe(true)
    write(repo, 'a.txt', 'ONE\ntwo\nthree\n')
    write(repo, 'new.md', '# new')
    const st = await git.status(repo)
    expect(st.branch).toBe('main')
    expect(st.unstaged.map((f) => f.path).sort()).toEqual(['a.txt', 'new.md'])
    const parent = path.dirname(repo)
    const found = await git.discover(parent, 1)
    expect(found).toContain(repo)
  })

  it('stages and unstages whole files, commits, amends', async () => {
    write(repo, 'b.txt', 'b\n')
    await git.stage(repo, ['b.txt'])
    expect((await git.status(repo)).staged.map((f) => f.path)).toEqual(['b.txt'])
    await git.unstage(repo, ['b.txt'])
    expect((await git.status(repo)).staged).toHaveLength(0)
    await git.stage(repo, ['b.txt'])
    const sha = await git.commit(repo, 'feat: add b')
    expect(sha).toMatch(/^[0-9a-f]{40}$/)
    await git.commit(repo, 'feat: add b (amended)', { amend: true })
    expect(await git.lastCommitMessage(repo)).toBe('feat: add b (amended)')
    expect((await git.log(repo)).length).toBe(2)
  })

  it('stages a single hunk and single lines', async () => {
    write(repo, 'a.txt', 'ONE\ntwo\nthree\nfour\nfive\nsix\nseven\neight\nnine\nTEN\n')
    const fd = await git.fileDiff(repo, 'a.txt', false)
    expect(fd!.hunks.length).toBe(2)
    await git.applyHunk(repo, 'a.txt', 1, 'stage')
    const staged = await git.fileDiff(repo, 'a.txt', true)
    expect(staged!.hunks.length).toBe(1)
    expect(staged!.hunks[0].lines.some((l) => l.text === 'TEN')).toBe(true)
    // unstage it again
    await git.applyHunk(repo, 'a.txt', 0, 'unstage')
    expect(await git.fileDiff(repo, 'a.txt', true)).toBeNull()
    // line-level: stage only the "+ONE" addition, not the "-one" removal
    const fd2 = await git.fileDiff(repo, 'a.txt', false)
    const idx = fd2!.hunks[0].lines.findIndex((l) => l.type === 'add' && l.text === 'ONE')
    await git.applyHunk(repo, 'a.txt', 0, 'stage', [idx])
    const idxContent = sh(repo, 'show', ':a.txt')
    expect(idxContent.startsWith('one\nONE\ntwo')).toBe(true)
    // discard remaining working changes of hunk 1 (TEN)
    const fd3 = await git.fileDiff(repo, 'a.txt', false)
    const tenHunk = fd3!.hunks.findIndex((h) => h.lines.some((l) => l.text === 'TEN'))
    await git.applyHunk(repo, 'a.txt', tenHunk, 'discard')
    expect(readFileSync(path.join(repo, 'a.txt'), 'utf8').endsWith('ten\n')).toBe(true)
  })

  it('provides diff contents for Monaco', async () => {
    write(repo, 'src/main.ts', 'export const x = 2\n')
    const c = await git.diffContents(repo, 'src/main.ts', { kind: 'unstaged' })
    expect(c.original).toBe('export const x = 1\n')
    expect(c.modified).toBe('export const x = 2\n')
    expect(c.language).toBe('typescript')
    await git.stage(repo, ['src/main.ts'])
    const s = await git.diffContents(repo, 'src/main.ts', { kind: 'staged' })
    expect(s.modified).toBe('export const x = 2\n')
    const sha = await git.commit(repo, 'change x')
    const d = await git.commitDetail(repo, sha)
    expect(d.files).toEqual([{ path: 'src/main.ts', status: 'M', origPath: undefined, additions: 1, deletions: 1 }])
    const cc = await git.diffContents(repo, 'src/main.ts', { kind: 'commit', sha })
    expect(cc.original).toContain('x = 1')
  })

  it('discards changes incl. untracked', async () => {
    write(repo, 'a.txt', 'changed\n')
    write(repo, 'junk.tmp', 'x')
    await git.discard(repo, ['a.txt', 'junk.tmp'])
    expect(existsSync(path.join(repo, 'junk.tmp'))).toBe(false)
    expect((await git.status(repo)).unstaged).toHaveLength(0)
  })

  it('manages branches, merge and conflicts', async () => {
    await git.createBranch(repo, 'feature/x')
    write(repo, 'a.txt', 'feature\n')
    commitAll(repo, 'feature change')
    await git.checkout(repo, 'main')
    write(repo, 'a.txt', 'main\n')
    commitAll(repo, 'main change')
    const br = await git.branches(repo)
    expect(br.map((b) => b.name).sort()).toEqual(['feature/x', 'main'])
    await expect(git.merge(repo, 'feature/x')).rejects.toThrow(/CONFLICT/)
    const st = await git.status(repo)
    expect(st.operation).toBe('MERGING')
    expect(st.conflicted.map((f) => f.path)).toEqual(['a.txt'])
    const v = await git.conflictVersions(repo, 'a.txt')
    expect(v.ours).toBe('main\n'); expect(v.theirs).toBe('feature\n')
    await git.resolveWith(repo, 'a.txt', 'theirs')
    await git.continueOp(repo)
    expect((await git.status(repo)).operation).toBeNull()
    const log = await git.log(repo, { all: true })
    expect(log[0].parents).toHaveLength(2)
    await git.renameBranch(repo, 'feature/x', 'feature/y')
    await git.deleteBranch(repo, 'feature/y')
    expect((await git.branches(repo)).map((b) => b.name)).toEqual(['main'])
  })

  it('aborts a conflicting merge', async () => {
    await git.createBranch(repo, 'b2')
    write(repo, 'a.txt', 'x\n'); commitAll(repo, 'x')
    await git.checkout(repo, 'main')
    write(repo, 'a.txt', 'y\n'); commitAll(repo, 'y')
    await expect(git.merge(repo, 'b2')).rejects.toThrow()
    await git.abortOp(repo)
    expect((await git.status(repo)).operation).toBeNull()
  })

  it('cherry-picks, reverts, resets, tags', async () => {
    await git.createBranch(repo, 'side')
    write(repo, 'c.txt', 'c\n'); commitAll(repo, 'add c')
    const sha = (await git.log(repo))[0].hash
    await git.checkout(repo, 'main')
    await git.cherryPick(repo, sha)
    expect(existsSync(path.join(repo, 'c.txt'))).toBe(true)
    await git.revert(repo, 'HEAD')
    expect(existsSync(path.join(repo, 'c.txt'))).toBe(false)
    await git.reset(repo, 'HEAD~2', 'hard')
    expect((await git.log(repo)).length).toBe(1)
    await git.createTag(repo, 'v1.0.0', undefined, 'release')
    await git.createTag(repo, 'light')
    const tags = await git.tags(repo)
    expect(tags.find((t) => t.name === 'v1.0.0')!.annotated).toBe(true)
    await git.deleteTag(repo, 'light')
    expect((await git.tags(repo)).map((t) => t.name)).toEqual(['v1.0.0'])
    expect((await git.reflog(repo)).length).toBeGreaterThan(3)
  })

  it('manages worktrees', async () => {
    const wtDir = path.join(mkdtempSync(path.join(tmpdir(), 'gitloom-wt-')), 'wt1')
    await git.addWorktree(repo, wtDir, { newBranch: 'wt-branch', base: 'main' })
    let wts = await git.worktrees(repo)
    expect(wts).toHaveLength(2)
    expect(wts[1].branch).toBe('wt-branch')
    expect(wts[0].isCurrent).toBe(true)
    expect(await git.isRepo(wtDir)).toBe(true)
    expect((await git.summary(wtDir)).isWorktree).toBe(true)
    await git.lockWorktree(repo, wtDir, true, 'testing')
    expect((await git.worktrees(repo))[1].locked).toBe(true)
    await git.lockWorktree(repo, wtDir, false)
    await git.removeWorktree(repo, wtDir)
    wts = await git.worktrees(repo)
    expect(wts).toHaveLength(1)
  })

  it('stashes', async () => {
    write(repo, 'a.txt', 'stashed\n')
    write(repo, 'u.txt', 'untracked\n')
    await git.stashPush(repo, 'wip', { includeUntracked: true })
    expect((await git.status(repo)).unstaged).toHaveLength(0)
    const list = await git.stashes(repo)
    expect(list[0].message).toContain('wip')
    const files = await git.stashFiles(repo, 0)
    expect(files.map((f) => f.path).sort()).toEqual(['a.txt', 'u.txt'])
    const c = await git.diffContents(repo, 'a.txt', { kind: 'stash', index: 0 })
    expect(c.modified).toBe('stashed\n')
    await git.stashApply(repo, 0, true)
    expect(readFileSync(path.join(repo, 'a.txt'), 'utf8')).toBe('stashed\n')
    expect(await git.stashes(repo)).toHaveLength(0)
  })

  it('fetch / pull / push against a bare remote', async () => {
    const bare = mkdtempSync(path.join(tmpdir(), 'gitloom-bare-'))
    sh(bare, 'init', '-q', '--bare', '-b', 'main')
    await git.addRemote(repo, 'origin', bare)
    await git.push(repo, { setUpstream: true })
    const clone = path.join(mkdtempSync(path.join(tmpdir(), 'gitloom-clone-')), 'c')
    await git.clone(bare, clone)
    sh(clone, 'config', 'user.name', 'T'); sh(clone, 'config', 'user.email', 't@x')
    write(clone, 'remote.txt', 'r\n'); commitAll(clone, 'remote commit')
    await git.push(clone)
    await git.fetch(repo)
    expect((await git.status(repo)).behind).toBe(1)
    await git.pull(repo)
    expect(existsSync(path.join(repo, 'remote.txt'))).toBe(true)
    expect((await git.remotes(repo))[0].name).toBe('origin')
    // checkout a remote-only branch creates a tracking branch
    sh(clone, 'checkout', '-q', '-b', 'remote-only'); sh(clone, 'push', '-q', '-u', 'origin', 'remote-only')
    await git.fetch(repo)
    await git.checkout(repo, 'origin/remote-only')
    expect((await git.status(repo)).branch).toBe('remote-only')
  })

  it('manages hooks and the llmwiki template', async () => {
    const h = await git.hooks(repo)
    expect(h.hooks.some((x) => x.name === 'post-commit')).toBe(true)
    await git.installHookTemplate(repo, 'llmwiki')
    let pc = (await git.hooks(repo)).hooks.find((x) => x.name === 'post-commit')!
    expect(pc.enabled).toBe(true)
    if (process.platform !== 'win32') expect(statSync(pc.path).mode & 0o111).not.toBe(0)
    write(repo, 'README.md', '# Demo\n\nA demo project.\n')
    await git.stage(repo, ['README.md'])
    await git.commit(repo, 'docs: readme')
    const idx = readFileSync(path.join(repo, 'docs/llmwiki/index.md'), 'utf8')
    expect(idx).toContain('LLM Wiki')
    expect(idx).toContain('A demo project.')
    expect(idx).toContain('docs: readme')
    const cl = readFileSync(path.join(repo, 'docs/llmwiki/changelog.md'), 'utf8')
    expect(cl).toContain('docs: readme')
    await git.setHookEnabled(repo, 'post-commit', false)
    pc = (await git.hooks(repo)).hooks.find((x) => x.name === 'post-commit')!
    expect(pc.enabled).toBe(false); expect(pc.exists).toBe(true)
    await git.setHookEnabled(repo, 'post-commit', true)
    expect((await git.readHook(repo, 'post-commit'))).toContain('llmwiki')
    // conventional commit-msg hook blocks bad messages
    await git.installHookTemplate(repo, 'conventional')
    write(repo, 'z.txt', 'z'); await git.stage(repo, ['z.txt'])
    await expect(git.commit(repo, 'bad message')).rejects.toThrow(/Conventional/)
    await git.commit(repo, 'chore: good message')
    await git.deleteHook(repo, 'commit-msg')
    expect((await git.hooks(repo)).hooks.find((x) => x.name === 'commit-msg')!.exists).toBe(false)
  })

  it('appends to .gitignore and reads repo info', async () => {
    await git.ignore(repo, 'dist/')
    await git.ignore(repo, 'dist/')
    expect(readFileSync(path.join(repo, '.gitignore'), 'utf8')).toBe('dist/\n')
    const info = await git.repoInfo(repo)
    expect(info.userName).toBe('Tester')
    writeFileSync(path.join(repo, '.gitattributes'), '*.bin filter=lfs diff=lfs merge=lfs -text\n')
    expect((await git.repoInfo(repo)).lfsUsed).toBe(true)
  })
})
